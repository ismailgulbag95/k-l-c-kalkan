int? shopEquipmentAtlasFrame(ShopItem item) {
  final row = switch (item.category) {
    'head' => 0,
    'body' => 1,
    'boots' => 2,
    _ => null,
  };
  final tier = int.tryParse(item.id.split('_').last);
  if (row == null || tier == null || tier < 1 || tier > 4) return null;
  return row * 4 + tier - 1;
}

